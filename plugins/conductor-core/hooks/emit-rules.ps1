<#
.SYNOPSIS
    SessionStart hook for the conductor-core plugin: emits this repo's rules as
    session context.

.DESCRIPTION
    Plugins cannot ship a CLAUDE.md/rules file that Claude Code reads automatically
    (see .claude/task-plan.md Phase 4) - a SessionStart hook emitting additionalContext
    is the documented workaround. This script reads hooks/rules.md, sitting alongside
    this script, and prints it as a SessionStart hookSpecificOutput.additionalContext
    JSON payload so that friends who install only this plugin (with no local
    .claude/rules/ of their own) still get the engineering + git-hygiene rules
    injected into every session.

    rules.md itself is machine-generated by scripts/build-plugins.ps1 from the two
    canonical .claude/rules/*.md files - this script only reads it, never edits it,
    so the rules content never drifts from the canonical source.

.NOTES
    Contract verified against Claude Code docs (code.claude.com/docs/en/hooks):
    a SessionStart hook may either print plain text to stdout (added as context
    verbatim) or print a JSON object containing hookSpecificOutput.additionalContext.
    This script uses the JSON form since it is the unambiguous, documented contract.

    Hook-safety: this script must always exit 0 - a broken or missing rules.md file
    must never block session start. Wrapped in try/catch/finally so any read failure
    (missing file, transient I/O error) degrades to a stderr warning and empty output
    rather than a non-zero exit / stack trace.
#>

try {
    # Locate rules.md next to this script rather than re-deriving CLAUDE_PLUGIN_ROOT
    # inside the script body - $PSScriptRoot is always correct for however pwsh was
    # invoked, and keeps this script's only external dependency (the plugin-root
    # substitution) confined to hooks.json's command line.
    $rulesPath = Join-Path -Path $PSScriptRoot -ChildPath 'rules.md'

    if (-not (Test-Path -LiteralPath $rulesPath -PathType Leaf)) {
        # [Console]::Error, not Write-Warning: pwsh's warning stream (3) is merged
        # into process stdout by default when run non-interactively, which would
        # make this warning itself get treated as SessionStart plain-text context -
        # the opposite of "no output if rules.md missing". Writing straight to the
        # OS-level stderr stream avoids that regardless of pwsh stream semantics.
        [Console]::Error.WriteLine("emit-rules.ps1: rules.md not found at '$rulesPath' - skipping rules injection.")
        exit 0
    }

    $rulesContent = Get-Content -LiteralPath $rulesPath -Raw -ErrorAction Stop

    $payload = [ordered]@{
        hookSpecificOutput = [ordered]@{
            hookEventName      = 'SessionStart'
            additionalContext  = $rulesContent
        }
    }

    # -Compress keeps the payload a single line; -Depth covers the nested object.
    $payload | ConvertTo-Json -Depth 5 -Compress
}
catch {
    [Console]::Error.WriteLine("emit-rules.ps1: failed to emit rules content - $($_.Exception.Message)")
}
finally {
    # Always succeed: a hook-script failure must never block session start.
    exit 0
}
